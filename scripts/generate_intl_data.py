#!/usr/bin/env python3
"""Generate compact Rust Intl tables from a pinned Unicode CLDR JSON archive."""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import tarfile
import urllib.request
from pathlib import Path

VERSION = "48.2.0"
ARCHIVE_SHA256 = "4f28298550dea43439986cd9ffb0a69cb73ba7d0b34a3c474760905ce8ce9e70"
ARCHIVE_URL = f"https://github.com/unicode-org/cldr-json/archive/refs/tags/{VERSION}.tar.gz"
PREFIX = f"cldr-json-{VERSION}/cldr-json/"
LOCALES = ("en", "en-GB", "de", "fr", "es", "ja", "zh-Hans", "ar", "hi", "ru")
OUTPUT = Path("crates/amazing-js/src/builtins_intl_data.rs")


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def archive_bytes(path: Path | None) -> bytes:
    data = path.read_bytes() if path else urllib.request.urlopen(ARCHIVE_URL, timeout=120).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != ARCHIVE_SHA256:
        raise SystemExit(f"CLDR archive SHA-256 mismatch: {digest}")
    return data


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, help="Use a previously downloaded pinned archive")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    tar = tarfile.open(fileobj=io.BytesIO(archive_bytes(args.archive)), mode="r:gz")

    def cldr(path: str) -> dict:
        member = tar.extractfile(PREFIX + path)
        if member is None:
            raise SystemExit(f"missing CLDR member: {path}")
        return json.load(member)

    lines = [
        "// Generated by scripts/generate_intl_data.py. Do not edit.",
        f"// Unicode CLDR JSON {VERSION}; archive SHA-256 {ARCHIVE_SHA256}.",
        "struct IntlNumberData {",
        "    locale: &'static str, numbering_system: &'static str,",
        "    decimal: &'static str, group: &'static str, plus: &'static str, minus: &'static str,",
        "    percent: &'static str, nan: &'static str, infinity: &'static str,",
        "    decimal_pattern: &'static str, percent_pattern: &'static str,",
        "    currency_pattern: &'static str, minimum_grouping: usize,",
        "}",
        "const INTL_NUMBER_DATA: &[IntlNumberData] = &[",
    ]
    for locale in LOCALES:
        main_data = cldr(f"cldr-numbers-full/main/{locale}/numbers.json")["main"][locale]["numbers"]
        numbering = main_data["defaultNumberingSystem"]
        symbols = main_data[f"symbols-numberSystem-{numbering}"]
        fields = [
            locale, numbering, symbols["decimal"], symbols["group"], symbols["plusSign"],
            symbols["minusSign"], symbols["percentSign"], symbols["nan"], symbols["infinity"],
            main_data[f"decimalFormats-numberSystem-{numbering}"]["standard"],
            main_data[f"percentFormats-numberSystem-{numbering}"]["standard"],
            main_data[f"currencyFormats-numberSystem-{numbering}"]["standard"],
        ]
        lines.append(
            "    IntlNumberData { locale: " + rust_string(locale)
            + ", numbering_system: " + rust_string(numbering)
            + ", decimal: " + rust_string(symbols["decimal"])
            + ", group: " + rust_string(symbols["group"])
            + ", plus: " + rust_string(symbols["plusSign"])
            + ", minus: " + rust_string(symbols["minusSign"])
            + ", percent: " + rust_string(symbols["percentSign"])
            + ", nan: " + rust_string(symbols["nan"])
            + ", infinity: " + rust_string(symbols["infinity"])
            + ", decimal_pattern: " + rust_string(fields[9])
            + ", percent_pattern: " + rust_string(fields[10])
            + ", currency_pattern: " + rust_string(fields[11])
            + ", minimum_grouping: " + str(int(main_data.get("minimumGroupingDigits", "1")))
            + " },"
        )
    lines.append("];")

    lines += [
        "struct IntlDateData { locale: &'static str, date: [&'static str; 4], time: [&'static str; 4],",
        "    date_time: [&'static str; 4], months_wide: [&'static str; 12], months_abbr: [&'static str; 12],",
        "    weekdays_wide: [&'static str; 7], weekdays_abbr: [&'static str; 7],",
        "    am: &'static str, pm: &'static str,",
        "}",
        "const INTL_DATE_DATA: &[IntlDateData] = &[",
    ]
    array = lambda values: "[" + ", ".join(map(rust_string, values)) + "]"
    for locale in LOCALES:
        date_data = cldr(f"cldr-dates-full/main/{locale}/ca-gregorian.json")["main"][locale]["dates"]["calendars"]["gregorian"]
        months = date_data["months"]["format"]
        days = date_data["days"]["format"]
        periods = date_data["dayPeriods"]["format"]["wide"]
        styles = ("full", "long", "medium", "short")
        weekdays = ("sun", "mon", "tue", "wed", "thu", "fri", "sat")
        lines.append(
            f"    IntlDateData {{ locale: {rust_string(locale)}, "
            f"date: {array(date_data['dateFormats'][style] for style in styles)}, "
            f"time: {array(date_data['timeFormats'][style] for style in styles)}, "
            f"date_time: {array(date_data['dateTimeFormats'][style] for style in styles)}, "
            f"months_wide: {array(months['wide'][str(n)] for n in range(1, 13))}, "
            f"months_abbr: {array(months['abbreviated'][str(n)] for n in range(1, 13))}, "
            f"weekdays_wide: {array(days['wide'][day] for day in weekdays)}, "
            f"weekdays_abbr: {array(days['abbreviated'][day] for day in weekdays)}, "
            f"am: {rust_string(periods['am'])}, pm: {rust_string(periods['pm'])} }},"
        )
    lines.append("];")

    lines += [
        "struct IntlListData { locale: &'static str, kind: &'static str, style: &'static str,",
        "    start: &'static str, middle: &'static str, end: &'static str, pair: &'static str,",
        "}",
        "const INTL_LIST_DATA: &[IntlListData] = &[",
    ]
    for locale in LOCALES:
        patterns = cldr(f"cldr-misc-full/main/{locale}/listPatterns.json")["main"][locale]["listPatterns"]
        for kind, cldr_kind in (("conjunction", "standard"), ("disjunction", "or"), ("unit", "unit")):
            for style, suffix in (("long", ""), ("short", "-short"), ("narrow", "-narrow")):
                pattern = patterns.get(f"listPattern-type-{cldr_kind}{suffix}", patterns[f"listPattern-type-{cldr_kind}"])
                lines.append(
                    f"    IntlListData {{ locale: {rust_string(locale)}, kind: {rust_string(kind)}, style: {rust_string(style)}, "
                    f"start: {rust_string(pattern['start'])}, middle: {rust_string(pattern['middle'])}, "
                    f"end: {rust_string(pattern['end'])}, pair: {rust_string(pattern['2'])} }},"
                )
    lines.append("];")

    lines += [
        "struct IntlRelativeData { locale: &'static str, unit: &'static str, style: &'static str,",
        "    future_one: &'static str, future_other: &'static str, past_one: &'static str, past_other: &'static str,",
        "    previous: &'static str, current: &'static str, next: &'static str,",
        "}",
        "const INTL_RELATIVE_DATA: &[IntlRelativeData] = &[",
    ]
    for locale in LOCALES:
        fields = cldr(f"cldr-dates-full/main/{locale}/dateFields.json")["main"][locale]["dates"]["fields"]
        for unit in ("year", "quarter", "month", "week", "day", "hour", "minute", "second"):
            for style, suffix in (("long", ""), ("short", "-short"), ("narrow", "-narrow")):
                field = fields.get(unit + suffix, fields[unit])
                future = field["relativeTime-type-future"]
                past = field["relativeTime-type-past"]
                get = lambda table, cat: table.get(f"relativeTimePattern-count-{cat}",
                                                   table.get("relativeTimePattern-count-other", "{0}"))
                lines.append(
                    f"    IntlRelativeData {{ locale: {rust_string(locale)}, unit: {rust_string(unit)}, style: {rust_string(style)}, "
                    f"future_one: {rust_string(get(future, 'one'))}, future_other: {rust_string(get(future, 'other'))}, "
                    f"past_one: {rust_string(get(past, 'one'))}, past_other: {rust_string(get(past, 'other'))}, "
                    f"previous: {rust_string(field.get('relative-type--1', ''))}, "
                    f"current: {rust_string(field.get('relative-type-0', ''))}, "
                    f"next: {rust_string(field.get('relative-type-1', ''))} }},"
                )
    lines.append("];")

    currency_fractions = cldr("cldr-core/supplemental/currencyData.json")["supplemental"]["currencyData"]["fractions"]
    currency_by_locale = {
        locale: cldr(f"cldr-numbers-full/main/{locale}/currencies.json")["main"][locale]["numbers"]["currencies"]
        for locale in LOCALES
    }
    currency_codes = sorted({code for currencies in currency_by_locale.values() for code in currencies
                             if len(code) == 3 and code.isascii() and code.isalpha()})
    lines += [
        "struct IntlCurrencyData { code: &'static str, digits: usize,",
        "    symbols: [&'static str; 10], narrow_symbols: [&'static str; 10], names: [&'static str; 10],",
        "}",
        "const INTL_CURRENCY_DATA: &[IntlCurrencyData] = &[",
    ]
    for code in currency_codes:
        digits = int(currency_fractions.get(code, currency_fractions["DEFAULT"])["_digits"])
        symbols = [currency_by_locale[locale].get(code, {}).get("symbol", code) for locale in LOCALES]
        narrow = [currency_by_locale[locale].get(code, {}).get("symbol-alt-narrow", symbols[index])
                  for index, locale in enumerate(LOCALES)]
        names = [currency_by_locale[locale].get(code, {}).get("displayName", code) for locale in LOCALES]
        lines.append(f"    IntlCurrencyData {{ code: {rust_string(code)}, digits: {digits}, "
                     f"symbols: {array(symbols)}, narrow_symbols: {array(narrow)}, names: {array(names)} }},")
    lines.append("];")
    currency_regions = cldr("cldr-core/supplemental/currencyData.json")["supplemental"]["currencyData"]["region"]
    active_currencies = sorted({code for entries in currency_regions.values() for entry in entries
                                for code, details in entry.items() if "_to" not in details
                                and len(code) == 3 and code.isascii() and code.isalpha()})
    lines.append("const INTL_SUPPORTED_CURRENCIES: &[&str] = &[")
    for code in active_currencies:
        lines.append(f"    {rust_string(code)},")
    lines.append("];")

    lines.append("struct IntlPluralRule { locale: &'static str, kind: &'static str, category: &'static str, rule: &'static str }")
    lines.append("const INTL_PLURAL_RULES: &[IntlPluralRule] = &[")
    for kind, filename, field in (
        ("cardinal", "plurals.json", "plurals-type-cardinal"),
        ("ordinal", "ordinals.json", "plurals-type-ordinal"),
    ):
        rules = cldr(f"cldr-core/supplemental/{filename}")["supplemental"][field]
        for locale in LOCALES:
            source = "zh" if locale == "zh-Hans" else locale.split("-")[0]
            for key, value in rules.get(source, {}).items():
                category = key.removeprefix("pluralRule-count-")
                condition = value.split("@")[0].strip()
                if condition:
                    lines.append(f"    IntlPluralRule {{ locale: {rust_string(locale)}, kind: {rust_string(kind)}, "
                                 f"category: {rust_string(category)}, rule: {rust_string(condition)} }},")
    lines.append("];")

    aliases = cldr("cldr-core/supplemental/aliases.json")["supplemental"]["metadata"]["alias"]
    for name, key in (
        ("INTL_LANGUAGE_ALIASES", "languageAlias"),
        ("INTL_SCRIPT_ALIASES", "scriptAlias"),
        ("INTL_REGION_ALIASES", "territoryAlias"),
        ("INTL_VARIANT_ALIASES", "variantAlias"),
    ):
        lines.append(f"const {name}: &[(&str, &str)] = &[")
        for source, entry in sorted(aliases[key].items()):
            replacement = entry["_replacement"].split()[0].replace("_", "-")
            lines.append(f"    ({rust_string(source)}, {rust_string(replacement)}),")
        lines.append("];")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(f"{args.output}: {len(lines)} lines")

    names = [
        "// Generated by scripts/generate_intl_data.py. Do not edit.",
        f"// Unicode CLDR JSON {VERSION}; archive SHA-256 {ARCHIVE_SHA256}.",
        "struct IntlDisplayEntry { kind: &'static str, code: &'static str, name: &'static str }",
        "const INTL_DISPLAY_DATA: &[(&str, &[IntlDisplayEntry])] = &[",
    ]
    for locale in LOCALES:
        identifier = locale.upper().replace("-", "_")
        names.append(f"    ({rust_string(locale)}, INTL_DISPLAY_{identifier}),")
    names.append("];")
    for locale in LOCALES:
        identifier = locale.upper().replace("-", "_")
        names.append(f'include!("builtins_intl_names_{locale.lower().replace("-", "_")}.rs");')
        records = [
            "// Generated by scripts/generate_intl_data.py. Do not edit.",
            f"const INTL_DISPLAY_{identifier}: &[IntlDisplayEntry] = &[",
        ]
        for filename, kind, field in (
            ("languages.json", "language", "languages"),
            ("territories.json", "region", "territories"),
            ("scripts.json", "script", "scripts"),
        ):
            source = cldr(f"cldr-localenames-full/main/{locale}/{filename}")["main"][locale]["localeDisplayNames"][field]
            for code, name in sorted(source.items()):
                if "-alt-" not in code:
                    records.append(
                        f"    IntlDisplayEntry {{ kind: {rust_string(kind)}, code: {rust_string(code)}, name: {rust_string(name)} }},"
                    )
        locale_names = cldr(f"cldr-localenames-full/main/{locale}/localeDisplayNames.json")["main"][locale]["localeDisplayNames"]
        for code, name in sorted(locale_names["types"].get("calendar", {}).items()):
            if "-alt-" not in code:
                records.append(
                    f"    IntlDisplayEntry {{ kind: \"calendar\", code: {rust_string(code)}, name: {rust_string(name)} }},"
                )
        fields = cldr(f"cldr-dates-full/main/{locale}/dateFields.json")["main"][locale]["dates"]["fields"]
        for code in ("era", "year", "quarter", "month", "week", "weekday", "day",
                     "dayPeriod", "hour", "minute", "second", "timeZoneName"):
            if code in fields:
                records.append(
                    f"    IntlDisplayEntry {{ kind: \"dateTimeField\", code: {rust_string(code)}, "
                    f"name: {rust_string(fields[code]['displayName'])} }},"
                )
        records.append("];")
        path = args.output.parent / f"builtins_intl_names_{locale.lower().replace('-', '_')}.rs"
        path.write_text("\n".join(records) + "\n")
        print(f"{path}: {len(records)} lines")
    path = args.output.parent / "builtins_intl_names.rs"
    path.write_text("\n".join(names) + "\n")


if __name__ == "__main__":
    main()
