#!/usr/bin/env python3
"""Generate Intl.Locale supplemental tables from the pinned CLDR JSON archive."""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import tarfile
import urllib.request
from pathlib import Path

VERSION = "48.2.0"
SHA256 = "4f28298550dea43439986cd9ffb0a69cb73ba7d0b34a3c474760905ce8ce9e70"
URL = f"https://github.com/unicode-org/cldr-json/archive/refs/tags/{VERSION}.tar.gz"
PREFIX = f"cldr-json-{VERSION}/cldr-json/"
OUTPUT = Path("crates/amazing-js/src/builtins_intl_locale_data.rs")
LIKELY_CHUNK = 3000
LOCALES = ("en", "en-GB", "de", "fr", "es", "ja", "zh-Hans", "ar", "hi", "ru")
DAYS = ("mon", "tue", "wed", "thu", "fri", "sat", "sun")
HOURS = {"H": "h23", "h": "h12", "K": "h11", "k": "h24"}


def source(path: Path | None) -> tarfile.TarFile:
    data = path.read_bytes() if path else urllib.request.urlopen(URL, timeout=120).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"CLDR archive SHA-256 mismatch: {digest}")
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    archive = source(args.archive)

    def cldr(path: str) -> dict:
        member = archive.extractfile(PREFIX + path)
        if member is None:
            raise SystemExit(f"missing CLDR member: {path}")
        return json.load(member)

    quoted = lambda value: json.dumps(value, ensure_ascii=False)
    array = lambda values: "&[" + ", ".join(map(quoted, values)) + "]"
    week = cldr("cldr-core/supplemental/weekData.json")["supplemental"]["weekData"]
    times = cldr("cldr-core/supplemental/timeData.json")["supplemental"]["timeData"]
    calendars = cldr("cldr-core/supplemental/calendarPreferenceData.json")["supplemental"]["calendarPreferenceData"]
    primary_zones = cldr("cldr-core/supplemental/primaryZones.json")["supplemental"]["primaryZones"]
    windows_zones = cldr("cldr-core/supplemental/windowsZones.json")["supplemental"]["windowsZones"]["mapTimezones"]
    zones_by_region: dict[str, set[str]] = {}
    for item in windows_zones:
        zone = item["mapZone"]
        zones_by_region.setdefault(zone["_territory"], set()).update(zone["_type"].split())
    for region, zone in primary_zones.items():
        zones_by_region.setdefault(region, set()).add(zone)
    likely = cldr("cldr-core/supplemental/likelySubtags.json")["supplemental"]["likelySubtags"]
    regions = set().union(*(set(week[key]) for key in ("firstDay", "weekendStart", "weekendEnd")))
    regions.update(key for key in times if len(key) in (2, 3) and key.upper() == key)
    regions.update(calendars)
    regions.update(zones_by_region)

    lines = [
        "// Generated by scripts/generate_intl_locale_data.py. Do not edit.",
        f"// Unicode CLDR JSON {VERSION}; archive SHA-256 {SHA256}.",
        "struct IntlLocaleRegionData {",
        "    region: &'static str, first_day: u8, weekend_start: u8, weekend_end: u8,",
        "    hour_cycles: &'static [&'static str], calendars: &'static [&'static str],",
        "    time_zones: &'static [&'static str],",
        "}",
        "const INTL_LOCALE_REGIONS: &[IntlLocaleRegionData] = &[",
    ]
    for region in sorted(regions):
        day = lambda key: DAYS.index(week[key].get(region, week[key]["001"])) + 1
        time = times.get(region, times["001"])
        hours = []
        for field in (time["_preferred"], time["_allowed"]):
            for symbol in field.split():
                cycle = HOURS.get(symbol[0])
                if cycle and cycle not in hours:
                    hours.append(cycle)
        calendar_ids = [("gregory" if value == "gregorian" else value)
                        for value in calendars.get(region, calendars["001"])]
        lines.append(
            "    IntlLocaleRegionData { region: " + quoted(region)
            + f", first_day: {day('firstDay')}, weekend_start: {day('weekendStart')}, weekend_end: {day('weekendEnd')}"
            + ", hour_cycles: " + array(hours) + ", calendars: " + array(calendar_ids)
            + ", time_zones: " + array(sorted(zones_by_region.get(region, ()))) + " },"
        )
    lines.append("];")
    likely_lines = []
    for language, expanded in sorted(likely.items()):
        if "-" in expanded:
            likely_lines.append(f"    ({quoted(language)}, {quoted(expanded)}),")
    lines.append("const INTL_LOCALE_PREFERENCES: &[(&str, &str, &str)] = &[")
    for locale in LOCALES:
        numbers = cldr(f"cldr-numbers-full/main/{locale}/numbers.json")["main"][locale]["numbers"]
        layout = cldr(f"cldr-misc-full/main/{locale}/layout.json")["main"][locale]["layout"]
        direction = "rtl" if layout["orientation"]["characterOrder"] == "right-to-left" else "ltr"
        lines.append(f"    ({quoted(locale)}, {quoted(numbers['defaultNumberingSystem'])}, {quoted(direction)}),")
    lines.append("];")
    args.output.write_text("\n".join(lines) + "\n")
    for index, start in enumerate(range(0, len(likely_lines), LIKELY_CHUNK)):
        chunk = [
            "// Generated by scripts/generate_intl_locale_data.py. Do not edit.",
            f"// Unicode CLDR JSON {VERSION}; archive SHA-256 {SHA256}.",
            f"const INTL_LIKELY_REGIONS_{index}: &[(&str, &str)] = &[",
            *likely_lines[start:start + LIKELY_CHUNK],
            "];",
        ]
        args.output.with_name(f"builtins_intl_likely_data_{index}.rs").write_text("\n".join(chunk) + "\n")


if __name__ == "__main__":
    main()
