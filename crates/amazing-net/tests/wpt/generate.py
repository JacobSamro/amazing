"""Transform the pinned upstream data into std-only Rust fixtures (no execution).

Run from any directory with Python 3. Each upstream object retains its array
index. USVString conversion replaces unpaired surrogates, as the WPT JS API does.
"""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent
raw = (root / 'urltestdata.json').read_bytes()
data = json.loads(raw)

def rust(value):
    value = value.encode('utf-16-le', 'surrogatepass').decode('utf-16-le', 'replace')
    return '"' + ''.join(
        '\\u{' + format(ord(c), 'x') + '}' if ord(c) < 32 or ord(c) > 126
        else '\\' + c if c in '\\"' else c for c in value
    ) + '"'

fields = ['href', 'origin', 'protocol', 'username', 'password', 'host',
          'hostname', 'port', 'pathname', 'search', 'hash']
lines = ['// Generated by generate.py; do not edit. WPT license: upstream-LICENSE.md.',
         '// JSON SHA-256: ' + hashlib.sha256(raw).hexdigest(),
         '&[']
for index, row in enumerate(data):
    if not isinstance(row, dict):
        continue
    base = 'Some(' + rust(row['base']) + ')' if row.get('base') is not None else 'None'
    expected = ','.join('Some(' + rust(row[f]) + ')' if f in row else 'None' for f in fields)
    lines.append('Case { index: ' + str(index) + ', input: ' + rust(row['input']) +
                 ', base: ' + base + ', failure: ' + str(row.get('failure', False)).lower() +
                 ', expected: [' + expected + '] },')
lines.append(']')
(root / 'cases.rs').write_text('\n'.join(lines) + '\n')
