"""Generate std-only Rust constants from pinned WPT setters_tests.json."""
import json
import pathlib

root = pathlib.Path(__file__).parent
data = json.loads((root / 'setters_tests.json').read_text())


def quote(value):
    # Escape each scalar once; replacing escape substrings in JSON text would
    # also alter literal backslash-b sequences in URL path cases.
    out = ['"']
    for char in value:
        if char == '\\':
            out.append('\\\\')
        elif char == '"':
            out.append('\\"')
        elif char == '\n':
            out.append('\\n')
        elif char == '\r':
            out.append('\\r')
        elif char == '\t':
            out.append('\\t')
        elif ord(char) < 0x20 or ord(char) == 0x7f:
            out.append(f'\\u{{{ord(char):04X}}}')
        else:
            out.append(char)
    return ''.join(out) + '"'


lines = [
    '// Generated by generate_setters.py from pinned WPT JSON.',
    '&[',
]
count = 0
for property_name, cases in data.items():
    if property_name == 'comment':
        continue
    for index, case in enumerate(cases):
        expected = ', '.join(f'({quote(k)}, {quote(v)})' for k, v in case['expected'].items())
        lines.append(
            f'    SetterCase {{ property: {quote(property_name)}, index: {index}, '
            f'comment: {quote(case.get("comment", ""))}, href: {quote(case["href"])}, '
            f'new_value: {quote(case["new_value"])}, expected: &[{expected}] }},'
        )
        count += 1
lines.extend([']', ''])
(root / 'setters_cases.rs').write_text('\n'.join(lines))
print(f'{count} URL setter cases')
