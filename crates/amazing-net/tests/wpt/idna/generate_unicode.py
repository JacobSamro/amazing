#!/usr/bin/env python3
"""Generate std-only UTS #46 tables from Unicode 17.0.0 source files.

Download the six files named in PROVENANCE.md into one directory, then run
`python3 generate_unicode.py <directory>`. SHA checks make regeneration pinned.
"""
import hashlib
import pathlib
import sys

HASHES = {
    "IdnaMappingTable.txt": "87f05505dc026fdb2bff16132bdc68a8014675836882a9a2b1844540ad3be382",
    "DerivedBidiClass.txt": "4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4",
    "DerivedJoiningType.txt": "f39ebe974825d6736aee15582250307aa532b2cfab3caf3f86bd23fddc9c5c4d",
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "DerivedCombiningClass.txt": "191463abfbd202703c6fd6776a92a23ac44ec65e0476a7f95aa91ca492cef29b",
    "DerivedNormalizationProps.txt": "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
}


def lines(root, name):
    raw = (root / name).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == HASHES[name], name
    return raw.decode("utf-8").splitlines()


def span(s):
    parts = s.strip().split("..")
    return int(parts[0], 16), int(parts[-1], 16)


def property_ranges(source, wanted=None):
    for line in source:
        body = line.split("#", 1)[0].strip()
        if not body or body.startswith("@"): continue
        bits = [b.strip() for b in body.split(";")]
        if wanted is None or bits[1] == wanted:
            yield (*span(bits[0]), bits[1])


def write_array(out, name, typ, rows, render, per_line=8):
    out.write(f"pub(super) const {name}: &[{typ}] = &[\n")
    for i in range(0, len(rows), per_line):
        out.write("    " + " ".join(render(row) + "," for row in rows[i:i+per_line]) + "\n")
    out.write("];\n")


def main(root):
    source = lines(root, "IdnaMappingTable.txt")
    statuses = {"valid": 0, "mapped": 1, "ignored": 2, "deviation": 3, "disallowed": 4}
    mapping, values = [], []
    for line in source:
        body = line.split("#", 1)[0].strip()
        if not body: continue
        bits = [b.strip() for b in body.split(";")]
        start, end = span(bits[0]); status = statuses[bits[1]]
        replacement = [int(cp, 16) for cp in bits[2].split()] if len(bits) > 2 else []
        offset = len(values); values.extend(replacement)
        mapping.append((start, end, status, offset, len(replacement)))
    assert mapping[0][0] == 0 and mapping[-1][1] == 0x10ffff
    assert all(mapping[i][1] + 1 == mapping[i+1][0] for i in range(len(mapping)-1))

    bidi = [(a,b,{"L":1,"R":2,"AL":3,"AN":4,"EN":5,"ES":6,"CS":7,"ET":8,"ON":9,"BN":10,"NSM":11}.get(v,0)) for a,b,v in property_ranges(lines(root,"DerivedBidiClass.txt"))]
    bidi = [r for r in bidi if r[2]]
    bidi.sort()
    joining = [(a,b,{"U":0,"R":1,"L":2,"D":3,"C":4,"T":5}[v]) for a,b,v in property_ranges(lines(root,"DerivedJoiningType.txt"))]
    joining = [r for r in joining if r[2]]
    joining.sort()
    ccc = [(a,b,int(v)) for a,b,v in property_ranges(lines(root,"DerivedCombiningClass.txt")) if int(v)]
    ccc.sort()

    exclusions = set()
    for a,b,_ in property_ranges(lines(root,"DerivedNormalizationProps.txt"),"Full_Composition_Exclusion"):
        exclusions.update(range(a,b+1))
    decomp, dvalues, compose, marks = [], [], [], []
    pending_range = None
    for line in lines(root,"UnicodeData.txt"):
        bits = line.split(";"); cp = int(bits[0],16); category = bits[2]
        if bits[1].endswith(", First>"):
            pending_range = (cp, category)
            continue
        if bits[1].endswith(", Last>"):
            if pending_range and category.startswith("M"):
                marks.append((pending_range[0],cp))
            pending_range = None
            continue
        if category.startswith("M"): marks.append((cp,cp))
        decomposition = bits[5]
        if not decomposition or decomposition.startswith("<"): continue
        parts = [int(v,16) for v in decomposition.split()]
        decomp.append((cp,len(dvalues),len(parts))); dvalues.extend(parts)
        if len(parts)==2 and cp not in exclusions:
            compose.append((parts[0],parts[1],cp))
    compose.sort()
    marks.sort()
    merged_marks = []
    for a,b in marks:
        if merged_marks and a <= merged_marks[-1][1]+1:
            merged_marks[-1] = (merged_marks[-1][0],max(b,merged_marks[-1][1]))
        else: merged_marks.append((a,b))
    outpath = pathlib.Path(__file__).resolve().parents[3] / "src/url/idna_data.rs"
    with outpath.open("w") as out:
        out.write("// Generated by tests/wpt/idna/generate_unicode.py from Unicode 17.0.0.\n")
        out.write("// See tests/wpt/idna/PROVENANCE.md. Do not edit by hand.\n")
        write_array(out,"MAPPING","(u32,u32,u8,u32,u8)",mapping,lambda r: f"({r[0]},{r[1]},{r[2]},{r[3]},{r[4]})")
        write_array(out,"MAP_VALUES","u32",values,str,16)
        for name,rows in [("BIDI",bidi),("JOINING",joining),("CCC",ccc)]:
            write_array(out,name,"(u32,u32,u8)",rows,lambda r: f"({r[0]},{r[1]},{r[2]})")
        write_array(out,"MARKS","(u32,u32)",merged_marks,lambda r: f"({r[0]},{r[1]})")
        write_array(out,"DECOMP","(u32,u32,u8)",decomp,lambda r: f"({r[0]},{r[1]},{r[2]})")
        write_array(out,"DECOMP_VALUES","u32",dvalues,str,16)
        write_array(out,"COMPOSE","(u32,u32,u32)",compose,lambda r: f"({r[0]},{r[1]},{r[2]})")
    print(outpath, outpath.stat().st_size, "bytes", sum(1 for _ in outpath.open()), "lines")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]))
