#!/usr/bin/env python3
"""Generate std-only WHATWG index and label tables; --check verifies bytes."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REVISION = "a985b62a9b45c17da3e17a9f0a0b4e30c34c4a8a"
HASHES = {
    "indexes.json": "b7c8961095f0b4cae8f4a16a5011e7c84047a60c1277e28ee8df9e56074ee509",
    "encodings.json": "078212b3697f60b81225b6671bd9da2604497abff0aa8e96e4d46605c02ac9e7",
}

def ident(name: str) -> str:
    return "".join(part[0].upper() + part[1:].lower() for part in
                   __import__("re").findall(r"[A-Za-z]+|[0-9]+", name))

def const(name: str) -> str:
    return "INDEX_" + "".join(c.upper() if c.isalnum() else "_" for c in name)

def array(name: str, values: list, width: int = 32) -> str:
    rows = [f"pub(crate) const {name}: [u32; {len(values)}] = ["]
    vals = ["u32::MAX" if value is None else str(value) for value in values]
    for i in range(0, len(vals), width): rows.append("    " + ", ".join(vals[i:i+width]) + ",")
    rows.append("];")
    return "\n".join(rows)

def reverse_array(name: str, values: list) -> str:
    # Encoding index pointer uses the first occurrence, except specific
    # overrides applied by the hand-written standard encoder.
    pairs = {}
    for pointer, cp in enumerate(values):
        if cp is not None: pairs.setdefault(cp, pointer)
    values = sorted(pairs.items())
    rows = [f"pub(crate) const {name}: [(u32, u32); {len(values)}] = ["]
    vals = [f"({cp}, {pointer})" for cp, pointer in values]
    for i in range(0, len(vals), 24): rows.append("    " + ", ".join(vals[i:i+24]) + ",")
    rows.append("];")
    return "\n".join(rows)

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for filename, expected in HASHES.items():
        digest = hashlib.sha256((ROOT / "data" / filename).read_bytes()).hexdigest()
        if digest != expected: raise SystemExit(f"{filename}: SHA-256 {digest}, expected {expected}")
    indexes = json.loads((ROOT / "data/indexes.json").read_text())
    encodings = [encoding for section in json.loads((ROOT / "data/encodings.json").read_text())
                 for encoding in section["encodings"]]
    header = f"// Generated by tools/generate.py from WHATWG encoding {REVISION}. Do not edit.\n"
    tables = [header]
    reverse = [header]
    for name, values in indexes.items():
        if name == "gb18030-ranges": continue
        tables.append(array(const(name), values))
        reverse.append(reverse_array("REVERSE_" + const(name)[6:], values))
    ranges = indexes["gb18030-ranges"]
    tables.append(f"pub(crate) const GB18030_RANGES: [(u32, u32); {len(ranges)}] = [")
    for i in range(0, len(ranges), 8):
        tables.append("    " + ", ".join(f"({p}, {c})" for p,c in ranges[i:i+8]) + ",")
    tables.append("];")
    tables.append("pub(crate) fn lookup(name: &str, pointer: usize) -> Option<u32> {\n    let table: &[u32] = match name {")
    reverse.append("pub(crate) fn reverse(name: &str, code_point: u32) -> Option<u32> {\n    let table: &[(u32,u32)] = match name {")
    for name in indexes:
        if name == "gb18030-ranges": continue
        tables.append(f'        "{name}" => &{const(name)},')
        reverse.append(f'        "{name}" => &REVERSE_{const(name)[6:]},')
    tables.append('        _ => return None,\n    };\n    table.get(pointer).copied().filter(|&cp| cp != u32::MAX)\n}')
    reverse.append('        _ => return None,\n    };\n    table.binary_search_by_key(&code_point, |&(cp, _)| cp).ok().map(|i| table[i].1)\n}')
    label_rows = [header, "#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]", "pub enum Encoding {"]
    for encoding in encodings: label_rows.append(f"    {ident(encoding['name'])},")
    label_rows.append("}\nimpl Encoding {\n    pub fn name(self) -> &'static str {\n        match self {")
    for encoding in encodings: label_rows.append(f'            Self::{ident(encoding["name"])} => "{encoding["name"].lower()}",')
    label_rows.append("        }\n    }\n}\n")
    labels = sorted((label, ident(encoding["name"])) for encoding in encodings for label in encoding["labels"])
    label_rows.append(f"pub(crate) const LABELS: [(&str, Encoding); {len(labels)}] = [")
    for label, var in labels: label_rows.append(f'    ("{label}", Encoding::{var}),')
    label_rows.append("];")
    outputs = {
        ROOT / "src/generated/tables.rs": "\n".join(tables) + "\n",
        ROOT / "src/generated/reverse.rs": "\n".join(reverse) + "\n",
        ROOT / "src/generated/labels.rs": "\n".join(label_rows) + "\n",
    }
    for path, value in outputs.items():
        if len(value.splitlines()) >= 4000: raise SystemExit(f"{path}: over line limit")
        if args.check:
            if not path.exists() or path.read_text() != value: raise SystemExit(f"{path}: generated mismatch")
        else: path.write_text(value)
    print("generated tables reproducible" if args.check else "generated tables written")

if __name__ == "__main__": main()
