// Extract the HTTP-header cases embedded in the pinned WPT HTML sources.
// Run with `node generate.mjs` from this directory after updating source/.
import fs from 'node:fs';
import vm from 'node:vm';

const sources = [
  'max-age.html', 'expires.html', 'path.html', 'invalid.html',
  'name.html', 'name-and-value.html', 'attributes.www.sub.html',
  'domain-child.sub.html',
  // Widened for NET-35: same httpCookieTest/httpRedirectCookieTest
  // convention, pulled from cookies/name, cookies/attributes,
  // cookies/attributes/resources, cookies/encoding, cookies/ordering/resources
  // and cookies/value in the pinned c2a2fce checkout.
  'name-ctl.html', 'secure.https.html', 'secure-non-secure-child.html',
  'path-redirect.html', 'charset.html', 'ordering-child.sub.html',
  'value.html', 'value-ctl.html',
];
let skipped = 0;
const cases = [];
for (const source of sources) {
  const html = fs.readFileSync(`source/${source}`, 'utf8');
  const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
  const script = scripts.at(-1)?.[1];
  if (!script) throw new Error(`missing inline script: ${source}`);
  const sandbox = {
    httpCookieTest(cookie, expected, name, defaultPath = true, allowFetchFailure = false) {
      if (allowFetchFailure) {
        // Real WPT: this covers cases where the underlying fetch() itself may
        // fail at the network layer (e.g. a header value containing a raw NUL,
        // LF or CR), in which case the test skips its assertions entirely.
        // There is no live network here to fail, so the case is dropped
        // rather than asserting either outcome.
        skipped++;
        return;
      }
      cases.push({source, cookie: Array.isArray(cookie) ? cookie : [cookie], expected,
                  name, defaultPath});
    },
    domCookieTest() {},
    cookieStringWithNameAndValueLengths(n, v) { return 't'.repeat(n) + '=' + '1'.repeat(v); },
    // secure-non-secure-child.html re-parents its testdriver context to the
    // opener window; irrelevant here since test_driver itself is stubbed out
    // (httpCookieTest never calls into the real testharness/testdriver).
    setTestContextUsingRootWindow() {},
    getCtlCharacters() {
      return [...Array(0x20).keys()].concat([0x7f])
        .map(i => ({code: i, chr: String.fromCharCode(i)}));
    },
  };
  sandbox.httpRedirectCookieTest = (cookie, expected, name, location) => {
    cases.push({source, cookie: Array.isArray(cookie) ? cookie : [cookie], expected,
                name, defaultPath: false, location});
  };
  const substituted = script
    .replaceAll('"{{host}}"', '"web-platform.test"')
    .replaceAll('"{{domains[www]}}"', '"www.web-platform.test"')
    .replaceAll('"{{domains[www1]}}"', '"www1.web-platform.test"')
    .replaceAll('"{{domains[www2.www]}}"', '"www2.www.web-platform.test"')
    .replaceAll('"{{ports[http][0]}}"', '"80"');
  vm.runInNewContext(substituted, sandbox,
                     {filename: source, timeout: 1000});
}
// JSON.stringify escapes 0x08/0x0C as the shorthand `\b`/`\f`, which are not
// valid Rust string escapes (unlike `\n`/`\t`/`\r`, which JSON and Rust both
// support); rewrite those two to `\u{..}` alongside the `\u00XX` -> `\u{XX}`
// substitution already needed for every other control character.
const rust = value => JSON.stringify(value)
  .replace(/\\b/g, '\\u{8}')
  .replace(/\\f/g, '\\u{c}')
  .replace(/\\u00([0-9a-f]{2})/g, '\\u{$1}');
const lines = [
  '// Generated by generate.mjs from pinned WPT HTML. Do not edit by hand.',
  'pub const CASES: &[(&str, &str, &[&str], &str, bool, Option<&str>)] = &[',
];
for (const {source, cookie, expected, name, defaultPath, location} of cases) {
  lines.push(`    (${rust(source)}, ${rust(name)}, &[${cookie.map(rust).join(', ')}], ${rust(expected)}, ${defaultPath}, ${location ? `Some(${rust(location)})` : 'None'}),`);
}
lines.push('];', '');
fs.writeFileSync('cases.rs', lines.join('\n'));
console.log(`${cases.length} HTTP cookie cases from ${sources.length} pinned WPT files ` +
            `(${skipped} allowFetchFailure cases skipped, no live network to fail)`);
