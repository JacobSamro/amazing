"""Convert four pinned WPT JSON corpora into std-only Rust fixtures.

The JSON is the source of truth. Each array index remains the runner's case id.
"""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent


def rust(value):
    value = value.encode("utf-16-le", "surrogatepass").decode("utf-16-le", "replace")
    return '"' + "".join(
        "\\u{" + format(ord(c), "x") + "}"
        if ord(c) < 32 or ord(c) > 126
        else "\\" + c if c in '\\"' else c
        for c in value
    ) + '"'


def option(value):
    return "None" if value is None else "Some(" + rust(value) + ")"


def byte_option(value):
    return "None" if value is None else "Some(&[" + ",".join(map(str, value)) + "])"


def write(name, entries):
    raw = (root / name).read_bytes()
    lines = [
        "// Generated by tests/wpt/generate.py. WPT license: upstream-LICENSE.md.",
        "// JSON SHA-256: " + hashlib.sha256(raw).hexdigest(),
        "&[",
        *entries(json.loads(raw)),
        "]",
    ]
    (root / name.replace(".json", ".rs")).write_text("\n".join(lines) + "\n")


write(
    "mime-types.json",
    lambda rows: [
        "(" + rust(row["input"]) + "," + option(row["output"]) + "),"
        for row in rows if isinstance(row, dict)
    ],
)
write(
    "generated-mime-types.json",
    lambda rows: [
        "(" + rust(row["input"]) + "," + option(row["output"]) + "),"
        for row in rows
    ],
)
write(
    "data-urls.json",
    lambda rows: [
        "(" + rust(row[0]) + "," + option(row[1]) + ","
        + byte_option(row[2] if len(row) > 2 else None) + "),"
        for row in rows
    ],
)
write(
    "base64.json",
    lambda rows: [
        "(" + rust(row[0]) + "," + byte_option(row[1]) + "),"
        for row in rows
    ],
)
