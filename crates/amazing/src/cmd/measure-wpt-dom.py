#!/usr/bin/env python3
"""Pinned DOM and URL source-level testharness baselines. Run on the build server.

No synthetic harness or edited upstream test is accepted. DOM inventories
tracked sources; URL selects pinned .any.js window variants generated by the
installed runner from the upstream AnyHtmlHandler template.
"""
import argparse
import collections
import concurrent.futures
import hashlib
import html.parser
import json
import math
from pathlib import Path
import os
import re
import subprocess
import sys
import tempfile
import threading

REVISION = 'c2a2fce69e5c2509d9dc28440ec8b42532e5c293'
FILE_STATUSES = ('pass', 'fail', 'timeout', 'error', 'unsupported')
SUBTEST_STATUSES = ('pass', 'fail', 'timeout', 'notrun', 'error')
PROOF = ('resources/test/tests/functional/order.html',
         'resources/test/tests/functional/assert-array-equals.html')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def encoded(value):
    return (json.dumps(value, ensure_ascii=True, sort_keys=True, separators=(',', ':')) + '\n').encode()


def git(root, *args):
    return subprocess.check_output(['git', '-C', str(root), *args])


def checkout_is_marker_pinned(root):
    # The venus build hosts have no git; scripts/ensure-wpt.sh extracts the
    # pinned revision from a GitHub tarball there instead and marks it with an
    # empty .pinned-<rev7> file (see that script's own convention -- the same
    # one wpt_harness.rs's checkout_is_marker_pinned() checks). On such a
    # checkout every git() call below fails ("not a git repository") even
    # though the tree is correctly pinned, so callers fall back to reading the
    # tarball's on-disk state directly, which IS the pinned revision's content
    # byte for byte.
    return (Path(root) / ('.pinned-' + REVISION[:7])).exists()


class Page(html.parser.HTMLParser):
    def __init__(self, text):
        super().__init__()
        self.harness = False
        self.expected = ''
        self.in_expected = False
        self.variants = []
        self.long_timeout = False
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'script':
            src = attrs.get('src', '')
            if re.search(r'(^|/)testharness\.js($|[?#])', src):
                self.harness = True
            self.in_expected = attrs.get('id') == 'expected'
        if tag == 'meta':
            if attrs.get('name') == 'variant':
                self.variants.append(attrs.get('content', ''))
            if attrs.get('name') == 'timeout' and attrs.get('content') == 'long':
                self.long_timeout = True

    def handle_endtag(self, tag):
        if tag == 'script':
            self.in_expected = False

    def handle_data(self, data):
        if self.in_expected:
            self.expected += data


def list_tree(root, suite, marker_pinned):
    if marker_pinned:
        # The tarball checkout's on-disk state under suite/ is definitionally
        # the pinned revision's tree (that's what extracted it), so a plain
        # filesystem walk stands in for `git ls-tree -r --name-only`. Emit
        # posix-style relative paths to match git's own output format.
        base = Path(root) / suite
        if not base.is_dir():
            return []
        return sorted(
            str(p.relative_to(root).as_posix())
            for p in base.rglob('*')
            if p.is_file()
        )
    return git(root, 'ls-tree', '-r', '--name-only', REVISION, '--', suite + '/').decode().splitlines()


def inventory(root, suite='dom', served=False):
    marker_pinned = checkout_is_marker_pinned(root)
    selected, excluded = [], []
    for name in list_tree(root, suite, marker_pinned):
        if suite == 'url' and not (name in ('url/url-constructor.any.js', 'url/url-setters.any.js',
                'url/url-setters-stripping.any.js') or re.fullmatch(r'url/urlsearchparams-[^/]+\.any\.js', name)):
            continue
        parts = Path(name).parts
        if any(p in ('resources', 'support') or (served and p in ('tools', 'templates')) for p in parts):
            excluded.append({'test': name, 'reason': 'support resource'})
            continue
        suffix = Path(name).suffix
        generated = re.search(r'\.(any|window|worker)\.js$', name)
        if suffix not in ('.html', '.htm', '.xhtml', '.xht', '.svg') and not generated:
            excluded.append({'test': name, 'reason': 'not a testharness test source'})
            continue
        data = (root / name).read_bytes()
        if not marker_pinned:
            original = git(root, 'show', REVISION + ':' + name)
            if data != original:
                raise RuntimeError('Modified upstream source: ' + name)
        page = Page(data.decode('utf-8-sig', errors='replace'))
        if not generated and not page.harness:
            excluded.append({'test': name, 'reason': 'no external testharness script (e.g. crash/reference/support)'})
            continue
        reason = None
        any_window = bool(name.endswith('.any.js') and suite in ('url', 'xhr', 'fetch', 'FileAPI', 'streams'))
        if generated and not any_window:
            reason = 'generated JavaScript test globals/worker wrappers are unsupported'
        elif any_window and re.search(rb'^//\s*META:\s*global=(.*)$', data, re.M) and not re.search(rb'^//\s*META:\s*global=.*\bwindow\b', data, re.M):
            reason = 'window global not selected by upstream metadata'
        elif suffix != '.html' and not any_window and not (served and suffix == '.htm'):
            reason = 'XML/SVG/non-HTML document parsing is unsupported'
        elif '.manual.' in name or '-manual.' in name:
            reason = 'manual interaction is unsupported'
        elif '.sub.' in name and not served:
            reason = 'WPT server template substitution is unsupported'
        elif '.https.' in name:
            reason = 'HTTPS test origin is unsupported by the local runner'
        elif page.variants:
            reason = 'WPT URL variants are unsupported by the local source-file runner'
        any_long = any_window and bool(re.search(rb'^//\s*META:\s*timeout=long$', data, re.M))
        selected.append({'test': name, 'sha256': digest(data), 'unsupported': reason,
                         'variants': page.variants, 'long_timeout': page.long_timeout or any_long})
    return {'wpt_revision': REVISION, 'unit': 'tracked test source file; not generated WPT URL',
            'selection_rule': suite + '/ pinned source-file selection; .any.js uses the upstream window wrapper',
            'selected': selected, 'excluded': excluded}


class WptServe:
    """One pinned-wptserve process per test file (see wpt-serve.py).

    The engine's token generator is deterministic, so concurrent or successive
    tests would otherwise share stash keys; a private server (and stash) per file
    keeps every test hermetic. web-platform.test hosts reach it through
    AMAZING_WPT_SHIM_ADDR, set on the harness child only.
    """
    errors = None  # (lock, path) for server-side handler errors

    def __init__(self, root, test):
        self.test = test
        self.log = tempfile.TemporaryFile()
        self.proc = subprocess.Popen(
            [sys.executable, str(Path(__file__).with_name('wpt-serve.py')), '--wpt-root', str(root)],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=self.log)
        line = self.proc.stdout.readline().decode().strip()
        if not line.startswith('ADDR '):
            self.proc.kill()
            raise RuntimeError('wptserve failed to start')
        self.addr = line[5:]

    def close(self):
        self.proc.stdin.close()
        try:
            self.proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self.proc.kill()
        self.log.seek(0)
        text = self.log.read().decode('utf-8', 'replace')
        self.log.close()
        if WptServe.errors and ('Internal server error' in text or os.environ.get('WPT_SERVE_TRACE')):
            lock, path = WptServe.errors
            with lock:
                with open(path, 'a') as out:
                    out.write('### ' + self.test + '\n' + text[:60000] + '\n')


def unsupported(entry, timeout):
    return {'schema': 1, 'suite': 'wpt', 'wpt_revision': REVISION, 'test': entry['test'],
            'viewport': [800, 600], 'timeout_ms': timeout, 'status': 'unsupported',
            'harness_status': None, 'detail': entry['unsupported'],
            'file_counts': {s: int(s == 'unsupported') for s in FILE_STATUSES},
            'counts': {s: 0 for s in SUBTEST_STATUSES}, 'subtests': []}


def run(exe, root, entry, timeout, served=False):
    if entry.get('unsupported'):
        return unsupported(entry, timeout)
    server = WptServe(root, entry['test']) if served else None
    env = dict(os.environ, AMAZING_WPT_SHIM_ADDR=server.addr) if server else None
    try:
        proc = subprocess.run([str(exe), 'wpt-harness', str(root), entry['test'], '800', '600', str(timeout)],
                              capture_output=True, encoding='utf-8', errors='strict',
                              timeout=timeout / 1000 + 30, env=env)
    finally:
        if server:
            server.close()
    result = json.loads(proc.stdout)
    if result.get('suite') != 'wpt' or result.get('wpt_revision') != REVISION:
        raise RuntimeError('Missing provenance: ' + proc.stdout)
    if result['test'] != entry['test'] or result['status'] not in FILE_STATUSES:
        raise RuntimeError('Invalid result identity/classification: ' + proc.stdout)
    if (proc.returncode == 0) != (result['status'] == 'pass'):
        raise RuntimeError('Exit/result mismatch: ' + proc.stdout)
    if sum(result['counts'].values()) != len(result['subtests']):
        raise RuntimeError('Subtest count mismatch: ' + proc.stdout)
    return result


def outcomes(records):
    # Timing-dependent diagnostic text is retained in raw records, but not in
    # the outcome hash. Names, statuses, counts and harness status are retained.
    return [{k: ([{field: s[field] for field in ('name', 'status')} for s in r[k]]
                   if k == 'subtests' else r[k])
             for k in ('test', 'status', 'harness_status', 'file_counts', 'counts', 'subtests')}
            for r in records]


def save_round(output, label, records):
    raw = b''.join(encoded(r) for r in records)
    (output / (label + '.jsonl')).write_bytes(raw)
    return {'raw_sha256': digest(raw), 'outcome_sha256': digest(encoded(outcomes(records))),
            'files': {s: sum(r['file_counts'][s] for r in records) for s in FILE_STATUSES},
            'subtests': {s: sum(r['counts'][s] for r in records) for s in SUBTEST_STATUSES}}


def prove(exe, root, output, timeout):
    marker_pinned = checkout_is_marker_pinned(root)
    expected = {}
    for name in PROOF:
        data = (root / name).read_bytes()
        if not marker_pinned and data != git(root, 'show', REVISION + ':' + name):
            raise RuntimeError('Modified proof test: ' + name)
        e = json.loads(Page(data.decode()).expected)
        assert e['summarized_status']['status_string'] == 'OK'
        codes = {'PASS': 0, 'FAIL': 1, 'TIMEOUT': 2, 'NOTRUN': 3, 'PRECONDITION_FAILED': 4}
        expected[name] = sorted((t['name'], codes[t['status_string']]) for t in e['summarized_tests'])
    rounds = []
    for number in (1, 2):
        records = [run(exe, root, {'test': name}, timeout) for name in PROOF]
        for r in records:
            actual = sorted((t['name'], t['status']) for t in r['subtests'])
            if r['harness_status'] != 0 or actual != expected[r['test']]:
                (output / 'proof-failure.json').write_bytes(encoded(r))
                raise RuntimeError('Upstream proof does not match expected names/statuses: ' + r['test'])
        if [r['status'] for r in records] != ['pass', 'fail']:
            raise RuntimeError('Known-pass/known-fail file classifications incorrect')
        rounds.append(save_round(output, 'proof-' + str(number), records))
    if rounds[0]['outcome_sha256'] != rounds[1]['outcome_sha256']:
        raise RuntimeError('Upstream harness proof unstable')
    return {'tests': PROOF, 'expected_source': 'unmodified upstream embedded expected JSON',
            'checks': 'exact subtest names/statuses, harness OK, file classifications, exit codes',
            'rounds': rounds}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--executable', type=Path, required=True)
    ap.add_argument('--wpt-root', type=Path, required=True)
    ap.add_argument('--output', type=Path, required=True)
    ap.add_argument('--proof-only', action='store_true')
    ap.add_argument('--suite', choices=('dom', 'url', 'xhr', 'fetch', 'FileAPI', 'streams'), default='dom')
    ap.add_argument('--jobs', type=int, default=3)
    ap.add_argument('--only', default='', help='comma-separated exact test paths (exploratory runs only)')
    ap.add_argument('--rounds', type=int, choices=(1, 2), default=2,
                    help='1 skips the repeat-stability round (exploratory runs only)')
    ap.add_argument('--wptserve', choices=('auto', 'on', 'off'), default='auto',
                    help="serve resources with the pinned wptserve (auto: xhr and fetch suites)")
    ap.add_argument('--timeout-multiplier', type=float, default=1.0,
                    help='multiply normal and long WPT deadlines (default: 1)')
    args = ap.parse_args()
    if args.jobs < 1 or args.jobs > 8:
        ap.error('--jobs must be 1..8')
    if not math.isfinite(args.timeout_multiplier) or args.timeout_multiplier <= 0:
        ap.error('--timeout-multiplier must be a finite positive number')
    normal_deadline = round(10000 * args.timeout_multiplier)
    long_deadline = round(60000 * args.timeout_multiplier)
    if normal_deadline < 1 or long_deadline < 1:
        ap.error('--timeout-multiplier yields a deadline below 1 ms')
    root, exe, output = args.wpt_root.resolve(), args.executable.resolve(), args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    marker_pinned = checkout_is_marker_pinned(root)
    if not marker_pinned and git(root, 'rev-parse', 'HEAD').decode().strip() != REVISION:
        raise RuntimeError('Wrong WPT revision')
    harness = (root / 'resources/testharness.js').read_bytes()
    if not marker_pinned and harness != git(root, 'show', REVISION + ':resources/testharness.js'):
        raise RuntimeError('Modified upstream harness')
    summary = {'wpt_revision': REVISION, 'harness_sha256': digest(harness),
               'executable_sha256': digest(exe.read_bytes()), 'viewport': [800, 600],
               'timeout_multiplier': args.timeout_multiplier,
               'normal_deadline_ms': normal_deadline, 'long_deadline_ms': long_deadline,
               'proof': prove(exe, root, output, normal_deadline)}
    (output / 'summary.json').write_bytes(encoded(summary))
    print('Upstream known-pass/known-fail proof verified twice', flush=True)
    if args.proof_only:
        print(json.dumps(summary), flush=True)
        return
    served = args.wptserve == 'on' or (args.wptserve == 'auto' and args.suite in ('xhr', 'fetch', 'FileAPI'))
    if served:
        WptServe.errors = (threading.Lock(), output / 'wptserve-errors.log')
    selection = inventory(root, args.suite, served)
    if args.only:
        wanted = set(args.only.split(','))
        selection['selected'] = [e for e in selection['selected'] if e['test'] in wanted]
    selection['wptserve'] = served
    (output / 'selection.json').write_bytes(encoded(selection))
    summary['selection_sha256'] = digest(encoded(selection))
    summary['selected_source_files'] = len(selection['selected'])
    summary['excluded_files'] = len(selection['excluded'])
    rounds, results = [], []
    for number in range(1, args.rounds + 1):
        records = []
        entries = selection['selected']
        def one(entry):
            return run(exe, root, entry, long_deadline if entry['long_timeout'] else normal_deadline, served)
        with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
            for r in pool.map(one, entries):
                records.append(r)
                if len(records) % 25 == 0:
                    print(f'{args.suite} round {number}: {len(records)}/{len(entries)} sources', flush=True)
        results.append(records)
        rounds.append(save_round(output, args.suite + '-' + str(number), records))
        print(json.dumps({'round': number, **rounds[-1]}), flush=True)
    changes = ([a['test'] for a, b in zip(outcomes(results[0]), outcomes(results[1])) if a != b]
               if len(results) > 1 else [])
    summary.update(rounds=rounds, stable=not changes, outcome_changes=changes)
    summary['by_directory'] = {}
    for r in results[0]:
        directory = str(Path(r['test']).parent).replace('\\', '/')
        summary['by_directory'].setdefault(directory, collections.Counter()).update(r['file_counts'])
    (output / 'summary.json').write_bytes(encoded(summary))
    print(json.dumps(summary), flush=True)
    if changes:
        raise SystemExit('Repeated baseline changed; inspect outcome_changes, do not claim stability')


if __name__ == '__main__':
    main()
